export const dakarDepartments = Array.from(new Set(dakarZones.map((zone) => zone.department)));

export function getCommunesByDepartment(department: string) {
  return Array.from(
    new Set(
      dakarZones
        .filter((zone) => zone.department === department)
        .map((zone) => zone.commune),
    ),
  );
}

export function getZonesByCommune(commune: string) {
  return dakarZones.filter((zone) => zone.commune === commune);
}

export function getZoneById(zoneId?: string) {
  return dakarZones.find((zone) => zone.id === zoneId);
}
